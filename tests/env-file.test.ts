import { existsSync, mkdtempSync, readFileSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';

import { afterEach, describe, expect, it } from 'vitest';

import {
  EnvFileError,
  MASK,
  formatEnvValue,
  isSecretKey,
  parseEnv,
  parseReference,
  readEnvFile,
  renderEnv,
  writeEnvFile,
} from '../src/config/envFile.js';

const dirs: string[] = [];

function tempEnv(contents = ''): string {
  const dir = mkdtempSync(join(tmpdir(), 'infagent-env-'));
  dirs.push(dir);
  const file = join(dir, '.env');
  if (contents) writeFileSync(file, contents);
  return file;
}

afterEach(() => {
  // The folders are tiny and temporary: best-effort cleanup.
  for (const dir of dirs.splice(0)) rmSync(dir, { recursive: true, force: true });
});

describe('parsing a .env', () => {
  it('keeps comments, blanks and order, and unquotes values', () => {
    const lines = parseEnv('# banner\nA=1\n\nB="two words" # trailing\nC=\nbroken line\n');
    // The trailing newline produces one last empty line: that is a blank, not
    // a lost line — the file is rendered back byte for byte.
    expect(lines.map((line) => line.kind)).toEqual([
      'comment',
      'entry',
      'blank',
      'entry',
      'entry',
      'other',
      'blank',
    ]);
    expect(lines[3]).toMatchObject({ key: 'B', value: 'two words' });
    expect(lines[4]).toMatchObject({ key: 'C', value: '' });
  });

  it('quotes only the values that need it', () => {
    expect(formatEnvValue('plain-1')).toBe('plain-1');
    expect(formatEnvValue('with space')).toBe('"with space"');
    expect(formatEnvValue('say "hi"')).toBe('"say \\"hi\\""');
    expect(formatEnvValue('')).toBe('');
  });

  it('knows which keys hold credentials', () => {
    for (const key of ['SUPABASE_ACCESS_TOKEN', 'SMTP_PASS', 'NVIDIA_API_KEY', 'DATABASE_URL']) {
      expect(isSecretKey(key), key).toBe(true);
    }
    for (const key of ['PORT', 'NODE_ENV', 'SMTP_HOST']) {
      expect(isSecretKey(key), key).toBe(false);
    }
  });
});

describe('reading the file', () => {
  it('never puts a secret value in the snapshot', () => {
    const file = tempEnv('PORT=8787\nSUPABASE_ACCESS_TOKEN=sbp_secret_value\n');
    const snapshot = readEnvFile(file);

    const token = snapshot.entries.find((entry) => entry.key === 'SUPABASE_ACCESS_TOKEN');
    expect(token?.value).toBeNull();
    expect(token?.masked).toBe(MASK);
    expect(token?.set).toBe(true);
    expect(JSON.stringify(snapshot)).not.toContain('sbp_secret_value');

    const port = snapshot.entries.find((entry) => entry.key === 'PORT');
    expect(port?.value).toBe('8787');
    expect(port?.secret).toBe(false);
  });

  it('lists reference keys the file does not mention yet', () => {
    const file = tempEnv('PORT=8787\n');
    const reference = [
      '# ---- supabase ----',
      '# Project used by the MCP server.',
      'SUPABASE_PROJECT_REF=x',
      '',
    ].join('\n');
    const snapshot = readEnvFile(file, reference);

    const entry = snapshot.entries.find((item) => item.key === 'SUPABASE_PROJECT_REF');
    expect(entry).toMatchObject({
      group: 'supabase',
      note: 'Project used by the MCP server.',
      set: false,
    });
  });

  it('reads groups and notes from the reference file', () => {
    const map = parseReference(
      '# Generated by a tool\n# ---- runtime ----\n# Port of the console\nPORT=1\n',
    );
    expect(map.get('PORT')).toEqual({ group: 'runtime', note: 'Port of the console' });
  });
});

describe('writing the file', () => {
  it('updates in place, appends new keys and keeps a backup', () => {
    const file = tempEnv('# banner\nPORT=8787\n\n# a comment\nNODE_ENV=production\n');
    const result = writeEnvFile(file, { updates: { PORT: '9000', NEW_KEY: 'yes' } });

    const written = readFileSync(file, 'utf8');
    expect(written).toContain('# banner');
    expect(written).toContain('PORT=9000');
    expect(written).toContain('NODE_ENV=production');
    expect(written).toContain('# a comment');
    expect(written).toContain('NEW_KEY=yes');
    expect(result.changed.sort()).toEqual(['NEW_KEY', 'PORT']);
    expect(result.backup).toBe(`${file}.bak`);
    expect(readFileSync(`${file}.bak`, 'utf8')).toContain('PORT=8787');
  });

  it('creates the file with owner-only permissions and no backup when new', () => {
    const file = tempEnv();
    const result = writeEnvFile(file, { updates: { PORT: '8787' } });
    expect(result.backup).toBeNull();
    expect(readFileSync(file, 'utf8')).toBe('PORT=8787\n');
    if (process.platform !== 'win32') {
      expect(statSync(file).mode & 0o777).toBe(0o600);
    }
  });

  it('removes a key without disturbing the rest', () => {
    const file = tempEnv('A=1\nB=2\nC=3\n');
    writeEnvFile(file, { remove: ['B'] });
    expect(readFileSync(file, 'utf8')).toBe('A=1\nC=3\n');
  });

  it('refuses a key a shell could not read, and writes nothing', () => {
    const file = tempEnv('PORT=8787\n');
    expect(() => writeEnvFile(file, { updates: { 'bad key': 'x' } })).toThrow(EnvFileError);
    expect(() => writeEnvFile(file, { updates: { 'A;rm -rf /': 'x' } })).toThrow(EnvFileError);
    expect(readFileSync(file, 'utf8')).toBe('PORT=8787\n');
  });

  it('updates process.env for the running server', () => {
    const file = tempEnv('PORT=8787\n');
    writeEnvFile(file, { updates: { INFAGENT_TEST_FLAG: 'on' } });
    expect(process.env['INFAGENT_TEST_FLAG']).toBe('on');
    delete process.env['INFAGENT_TEST_FLAG'];
  });

  it('round-trips through render without losing lines', () => {
    const source = '# a\nA=1\n\n# b\nB=2\n';
    const rendered = renderEnv(parseEnv(source), new Map(), new Set());
    expect(rendered).toBe(source);
    expect(existsSync(tempEnv(source))).toBe(true);
  });
});
